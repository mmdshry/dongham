const byCode = new Map(CURRENCY_CATALOG.map((c) => [c.code, c]));

export function currencyInfo(code: string): CurrencyInfo {
  return (
    byCode.get(code.toUpperCase()) || {
      code: code.toUpperCase(),
      flag: '🏳️',
      countryFa: code.toUpperCase(),
      nameFa: code.toUpperCase(),
      group: 'other',
    }
  );
}

export function periodCurrencyOptions(extraCodes: string[] = []): CurrencyInfo[] {
  const seen = new Set<string>();
  const out: CurrencyInfo[] = [];
  for (const item of [...CURRENCY_CATALOG, ...extraCodes.map((c) => currencyInfo(c))]) {
    if (seen.has(item.code)) continue;
    seen.add(item.code);
    out.push(item);
  }
  return out;
}

export function searchCurrencies(query: string, extraCodes: string[] = []): CurrencyInfo[] {
  const q = query.trim().toLowerCase();
  const list = periodCurrencyOptions(extraCodes);
  if (!q) return list;
  return list.filter((c) =>
    [c.code, c.countryFa, c.nameFa, c.flag].some((part) => part.toLowerCase().includes(q)),
  );
}

/** Browse/search list: live rates visible before pinning. Empty query → priced codes plus IRR. */
export function browseRateCurrencies(
  query: string,
  rates: Record<string, number> = {},
  watch: string[] = [],
): CurrencyInfo[] {
  const watched = new Set(watch);
  const extra = Object.keys(rates);
  const list = searchCurrencies(query, extra).filter((c) => c.code !== 'IRT' && !watched.has(c.code));
  if (query.trim()) return list;
  return list.filter((c) => c.code === 'IRR' || (rates[c.code] || 0) > 0);
}

/** Displayed toman-per-unit. 1 IRR = 0.1 IRT. */
export function displayTomanRate(code: string, rate?: number): number {
  if (code === 'IRR') return 0.1;
  return rate && rate > 0 ? rate : 0;
}
